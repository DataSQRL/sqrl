// Remark plugin for docs and blog posts that serves the optimized images generated by
// scripts/optimize-images.mjs:
//   - Markdown images (![alt](/img/x.png)) and JSX <img> tags that reference a PNG or JPEG under
//     /img/ are pointed at the WebP version in static-generated/
//   - JSX <img> tags are lazy loaded and get the width and height of the image, so browsers reserve the space before the
//     image loads; Docusaurus adds them to Markdown images itself. Use style={{width: '50%'}} rather
//     than width="50%" to scale an image, since a width attribute disables this.
// Must run before the Docusaurus default plugins (beforeDefaultRemarkPlugins), whose image plugin
// then resolves the WebP version from the static directories.

import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const RASTER = /\.(png|jpe?g)$/i;
// src={useBaseUrl('/img/...')}
const USE_BASE_URL = /^\s*useBaseUrl\(\s*(['"])(\/img\/[^'"]+)\1\s*\)\s*$/;

function* nodes(tree) {
  yield tree;
  for (const child of tree.children ?? []) yield* nodes(child);
}

export default function optimizedImages({staticDir, generatedDir, baseUrl = '/'}) {
  const prefix = baseUrl.replace(/\/$/, '');
  const sizes = new Map();

  // Path of the WebP version of a /img/ PNG or JPEG, if there is one
  function webpUrl(url) {
    if (!url.startsWith('/img/') || !RASTER.test(url)) return null;
    const webp = url.replace(RASTER, '.webp');
    return fs.existsSync(path.join(generatedDir, webp)) ? webp : null;
  }

  async function size(url) {
    const file = [generatedDir, staticDir].map((dir) => path.join(dir, url)).find(fs.existsSync);
    if (!file) return null;
    if (!sizes.has(file)) {
      sizes.set(file, sharp(file).metadata().then(({width, height}) => (width && height ? {width, height} : null)));
    }
    return sizes.get(file);
  }

  async function processJsxImage(node) {
    const attribute = (name) => node.attributes.find((a) => a.type === 'mdxJsxAttribute' && a.name === name);
    const src = attribute('src');
    if (!src?.value) return;
    let url = typeof src.value === 'string' ? src.value : src.value.value?.match(USE_BASE_URL)?.[2];
    if (!url) return;

    const webp = webpUrl(url);
    if (webp) {
      url = webp;
      src.value = typeof src.value === 'string' ? webp : prefix + webp;
    } else if (!url.startsWith('/img/')) {
      return;
    }

    for (const [name, value] of [['loading', 'lazy'], ['decoding', 'async']]) {
      if (!attribute(name)) node.attributes.push({type: 'mdxJsxAttribute', name, value});
    }
    if (attribute('width') || attribute('height')) return;
    const dimensions = await size(url);
    if (!dimensions) return;
    node.attributes.push(
      {type: 'mdxJsxAttribute', name: 'width', value: String(dimensions.width)},
      {type: 'mdxJsxAttribute', name: 'height', value: String(dimensions.height)},
    );
  }

  return async (tree) => {
    const tasks = [];
    for (const node of nodes(tree)) {
      if (node.type === 'image') {
        node.url = webpUrl(node.url) ?? node.url;
      } else if ((node.type === 'mdxJsxFlowElement' || node.type === 'mdxJsxTextElement') && node.name === 'img') {
        tasks.push(processJsxImage(node));
      }
    }
    await Promise.all(tasks);
  };
}
